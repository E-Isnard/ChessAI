MATE_SCORE = 100000


def eval_board(b: chess.Board) -> int:
    """Static evaluation from the perspective of the side to move."""
    if b.is_checkmate():
        return -MATE_SCORE

    if b.is_stalemate() or b.is_insufficient_material() or b.can_claim_draw():
        return 0

    score = 0
    for square, piece in b.piece_map().items():
        val = PIECE_VALUES[piece.piece_type]

        # Positional bonuses using Piece-Square Tables
        table = PST.get(piece.piece_type)
        if table:
            # Table is defined from White's perspective (rank 8 to rank 1).
            # chess.Square index 0 is a1 (bottom left). Mirror for black:
            table_idx = 63 - (square if piece.color == chess.WHITE else chess.square_mirror(square))
            val += table[table_idx]

        # Bonus for Rooks on 7th rank (rank 6 in 0-indexed coords for White, rank 1 for Black)
        if piece.piece_type == chess.ROOK:
            rank = chess.square_rank(square)
            if (piece.color == chess.WHITE and rank == 6) or (piece.color == chess.BLACK and rank == 1):
                val += 25

        score += val if piece.color == chess.WHITE else -val

    return score if b.turn == chess.WHITE else -score
